import { useState } from 'react';
import { useReports } from '../data';

/** The 37 morning reports of the live period, as written (Polish), shown as plain text. */
export function Archive() {
  const loaded = useReports();
  const [selected, setSelected] = useState<string | null>(null);
  if (loaded.state === 'loading') return <p className="status">Loading reports.</p>;
  if (loaded.state === 'error') return <p className="status error">The reports could not be loaded ({loaded.message}).</p>;
  const reports = loaded.data.reports;
  const current = reports.find((r) => r.date === selected) ?? reports[reports.length - 1];
  return (
    <section className="archive">
      <p className="lead">
        Daily reports generated by the bot, {reports[0]?.date} to {reports[reports.length - 1]?.date}, covering the live-capital period; the last
        few were generated automatically after the project closed on 2026-09-22. They are in Polish, as written; private network addresses are
        masked.
      </p>
      <div className="archive-grid">
        <ul className="report-list" aria-label="Reports by date">
          {reports.map((r) => (
            <li key={r.date}>
              <button type="button" className={r.date === current?.date ? 'link active' : 'link'} onClick={() => setSelected(r.date)}>
                {r.date}
              </button>
            </li>
          ))}
        </ul>
        {current && (
          <article className="report">
            <h2>{current.title}</h2>
            <p className="meta">{current.file}</p>
            <pre className="report-text">{current.text}</pre>
          </article>
        )}
      </div>
    </section>
  );
}
