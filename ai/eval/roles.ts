/**
 * Step 6.2 (b): span roles and facts, from one reviewed JSON file (ai/eval/review/roles-*.json).
 *   npx tsx ai/eval/roles.ts review <roles.json> <out.md>   write the review file
 *   npx tsx ai/eval/roles.ts apply <roles.json>             write the roles into ai/eval/golden.jsonl
 *
 * The review file prints, for every span, the first and last line of its text beside the fact letters, so a reviewer
 * reads text against fact, not a line number against a description (the step 6.2 (a) dated-09 card mapped three
 * spans to the wrong facts that way). Both commands refuse a roles file that drops one of the question's current
 * spans without naming it in `replaces`, so nothing is lost silently.
 */
import { readFileSync, writeFileSync } from 'fs';
import type { Evidence, GoldenQuestion, Role } from './golden';
import { cell, ends, short } from './span-text';

interface SpanRole {
  file: string;
  lines: [number, number];
  role: Role;
  facts?: string[];
  reason: string;
  add?: boolean;
  replaces?: [number, number];
}
interface RolesFile {
  version: string;
  batch: string;
  questions: Record<string, { facts: Record<string, string>; spans: SpanRole[] }>;
}

const GOLDEN = 'ai/eval/golden.jsonl';
const key = (file: string, lines: [number, number]) => `${file}:${lines[0]}-${lines[1]}`;

function load(rolesPath: string) {
  const roles = JSON.parse(readFileSync(rolesPath, 'utf8')) as RolesFile;
  const golden = readFileSync(GOLDEN, 'utf8')
    .split('\n')
    .filter((l) => l.trim())
    .map((l) => JSON.parse(l) as GoldenQuestion);
  for (const [id, r] of Object.entries(roles.questions)) {
    const q = golden.find((g) => g.id === id);
    if (!q) throw new Error(`${id} is not in ${GOLDEN}`);
    const covered = new Set(r.spans.map((s) => key(s.file, s.replaces ?? s.lines)));
    const lost = q.evidence.filter((e) => !covered.has(key(e.file, e.lines)));
    if (lost.length) throw new Error(`${id}: current spans missing from the roles file: ${lost.map((e) => key(e.file, e.lines)).join(', ')}`);
    for (const s of r.spans) {
      const known = q.evidence.some((e) => key(e.file, e.lines) === key(s.file, s.replaces ?? s.lines));
      if (!known && !s.add) throw new Error(`${id}: ${key(s.file, s.lines)} is new but not marked "add"`);
      for (const f of s.facts ?? []) if (!(f in r.facts)) throw new Error(`${id}: unknown fact ${f}`);
    }
  }
  return { roles, golden };
}

function review(rolesPath: string, out: string) {
  const { roles } = load(rolesPath);
  const md: string[] = [
    `# Golden v${roles.version} span roles: ${roles.batch}`,
    '',
    `Generated by \`npx tsx ai/eval/roles.ts review ${rolesPath} ${out}\` from the reviewed roles file; do not edit by`,
    'hand. Each span shows its first and last line as they stand in the corpus. Read the text against the fact letters:',
    'a span is required only if a reader could state those facts from it alone.',
    '',
  ];
  for (const [id, r] of Object.entries(roles.questions)) {
    md.push(`## ${id}`, '');
    for (const [f, text] of Object.entries(r.facts)) {
      const n = r.spans.filter((s) => s.facts?.includes(f)).length;
      md.push(`- **${f}**: ${text}${n ? ` (${n} span${n > 1 ? 's' : ''})` : ' (**no span**)'}`);
    }
    md.push('', '| span | change | role | facts | first line | last line | reason |', '|---|---|---|---|---|---|---|');
    for (const s of r.spans) {
      const change = s.add ? 'added' : s.replaces ? `was ${s.replaces[0]}-${s.replaces[1]}` : '';
      const [first, last] = ends(s.file, s.lines);
      md.push(
        `| ${short(s.file)}:${s.lines[0]}-${s.lines[1]} | ${change} | ${s.role} | ${(s.facts ?? []).join(', ') || '-'} | ${cell(first)} | ${cell(last)} | ${cell(s.reason)} |`,
      );
    }
    md.push('');
  }
  writeFileSync(out, md.join('\n'));
  console.log(`wrote ${out}: ${Object.keys(roles.questions).length} questions`);
}

function apply(rolesPath: string) {
  const { roles, golden } = load(rolesPath);
  for (const q of golden) {
    const r = roles.questions[q.id];
    if (!r) continue;
    const added = r.spans.filter((s) => s.add).map((s) => key(s.file, s.lines));
    const widened = r.spans.filter((s) => s.replaces).map((s) => `${key(s.file, s.replaces!)} to ${s.lines[0]}-${s.lines[1]}`);
    q.evidence = r.spans.map((s): Evidence => ({ file: s.file, lines: s.lines, role: s.role, ...(s.facts ? { facts: s.facts } : {}) }));
    q.facts = r.facts;
    const parts = [`span roles and facts marked (step 6.2 b, ${roles.batch})`];
    if (added.length) parts.push(`added ${added.join(', ')}`);
    if (widened.length) parts.push(`widened ${widened.join(', ')}`);
    q.notes = `${q.notes ?? ''} v${roles.version}: ${parts.join('; ')}.`.trim();
  }
  writeFileSync(GOLDEN, golden.map((q) => JSON.stringify(q)).join('\n') + '\n');
  console.log(`applied ${Object.keys(roles.questions).length} questions to ${GOLDEN}`);
}

const [cmd, rolesPath, out] = process.argv.slice(2);
if (cmd === 'review' && rolesPath && out) review(rolesPath, out);
else if (cmd === 'apply' && rolesPath) apply(rolesPath);
else {
  console.error('usage: roles.ts review <roles.json> <out.md> | apply <roles.json>');
  process.exit(1);
}
